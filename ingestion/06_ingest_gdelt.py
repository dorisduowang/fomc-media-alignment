"""Official GDELT 2.0 GKG -> versioned S3 JSONL, restartable by shard.

Use with the download plan generated by Jerry_GDELT_2015_2025_workflow.ipynb.
Each ZIP is downloaded to a temporary file, checked against its official size/MD5,
then parsed row-by-row. The data are GKG metadata, NOT article full text.

Requires: boto3, requests (python-dotenv optional).
The classification rules in gdelt_filter_rules_v1.json must be reviewed and frozen
BEFORE confirmatory holdout analysis. A SHA256 of these rules is recorded in
EVERY shard manifest and extracted record.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import io
import json
import os
import re
import shutil
import sys
import tempfile
import time
import zipfile
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlsplit
from zoneinfo import ZoneInfo

import boto3
import requests
from botocore.exceptions import ClientError

try:
    from dotenv import load_dotenv
    load_dotenv(Path(__file__).resolve().parent.parent / ".env")
except ImportError:
    pass

csv.field_size_limit(32 * 1024 * 1024)
EASTERN = ZoneInfo("America/New_York")
STAMP_RE = re.compile(r"^\d{14}$")
MD5_RE = re.compile(r"^[0-9a-fA-F]{32}$")
ARCHIVE_RE = re.compile(r"^/gdeltv2/(\d{14})\.gkg\.csv\.zip$", re.I)
RUN_SCHEMA_VERSION = "gkg21_https_manifest_v2"


class LocalLake:
    """Use the same shard keys and checkpoints for a local pilot."""

    def __init__(self, root):
        self.root = Path(root).resolve()

    def _path(self, key):
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise ValueError(f"Key is outside the local lake: {key}")
        return path

    def _write(self, key, source):
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".", delete=False) as temp:
            temp_path = Path(temp.name)
        try:
            with temp_path.open("wb") as handle:
                shutil.copyfileobj(source, handle)
            temp_path.replace(path)
        finally:
            temp_path.unlink(missing_ok=True)

    def put_object(self, *, Bucket, Key, Body, ContentType):
        self._write(Key, io.BytesIO(Body))

    def upload_file(self, filename, bucket, key, ExtraArgs):
        with open(filename, "rb") as source:
            self._write(key, source)

    def get_object(self, *, Bucket, Key):
        try:
            return {"Body": io.BytesIO(self._path(Key).read_bytes())}
        except FileNotFoundError as exc:
            raise ClientError({"Error": {"Code": "NoSuchKey"}}, "GetObject") from exc

    def head_object(self, *, Bucket, Key):
        if not self._path(Key).is_file():
            raise ClientError({"Error": {"Code": "NoSuchKey"}}, "HeadObject")


def parse_tone(tone_str):
    if not tone_str:
        return {}
    parts = tone_str.split(",")
    names = ["tone", "positive_score", "negative_score", "polarity",
             "activity_ref_density", "self_group_ref_density", "word_count"]
    try:
        values = [float(part) if part else None for part in parts[:7]]
        if len(values) >= 7 and values[6] is not None:
            values[6] = int(values[6])
        return dict(zip(names, values))
    except ValueError:
        return {"raw_tone": tone_str}


def parse_themes(value):
    return [v.strip().split(",")[0] for v in (value or "").split(";") if v.strip()]


def parse_orgs(value):
    return [v.strip().split(",")[0] for v in (value or "").split(";") if v.strip()]


def parse_persons(value):
    return [v.strip().split(",")[0] for v in (value or "").split(";") if v.strip()]


def parse_locations(value):
    locs = []
    for block in (value or "").split(";"):
        parts = block.split("#")
        if len(parts) >= 3:
            locs.append({"type": parts[0].strip(), "full_name": parts[1].strip(),
                         "country_code": parts[2].strip(),
                         "adm1_code": parts[3].strip() if len(parts) > 3 else ""})
    return locs


def normalize_domain(value):
    value = (value or "").strip().lower()
    if "://" in value:
        value = urlsplit(value).hostname or ""
    else:
        value = value.split("/")[0].split(":")[0]
    return value[4:] if value.startswith("www.") else value


def allowed_domain(value, allowed):
    value = normalize_domain(value)
    return bool(value) and any(value == domain or value.endswith("." + domain)
                               for domain in allowed)


def phrase_in(text, phrase):
    # Token-boundary regex avoids matches such as 'fed' in 'federalized'.
    phrase = phrase.lower()
    return re.search(r"(?<![a-z0-9])" + re.escape(phrase) + r"(?![a-z0-9])", text) is not None


def classify(themes, orgs, persons, url, rules):
    theme_set = {x.upper() for x in themes}
    combined = " ".join([*orgs, *persons, url]).lower().replace("_", "-")
    # An explicit Fed reference AND policy context are both required.
    entity = any(phrase_in(combined, x) for x in rules["fed_entities"]) or any(
        phrase_in(combined, x) for x in rules["named_fed_officials"])
    context_text = (combined + " " + " ".join(themes).lower().replace("_", "-"))
    context = any(phrase_in(context_text, x) for x in rules["policy_context"])
    direct = bool(entity and context)
    broad = direct or bool(theme_set.intersection(rules["broad_themes"])) or any(
        phrase_in(combined, x) for x in rules["broad_keywords"])
    return direct, broad


def utc_doc_timestamp(value):
    # GKG DATE column is YYYYMMDDHHMMSS in UTC; do not infer from row ID.
    value = (value or "").strip()
    if not STAMP_RE.fullmatch(value):
        raise ValueError(f"Invalid GKG timestamp: {value!r}")
    return datetime.strptime(value, "%Y%m%d%H%M%S").replace(tzinfo=timezone.utc)


def record_from_row(row, shard, rules, rules_hash):
    if len(row) != 27:
        raise ValueError(f"Expected 27 GKG 2.1 fields; got {len(row)}")
    if "-T" in row[0]:  # exclude translated stream
        return None
    domain = normalize_domain(row[3])
    if not allowed_domain(domain, rules["allow_domains"]):
        return None
    themes = parse_themes(row[7])
    organizations = parse_orgs(row[13])
    persons = parse_persons(row[11])
    direct, broad = classify(themes, organizations, persons, row[4], rules)
    if not broad:
        return None
    dt = utc_doc_timestamp(row[1])
    text = " ".join([*themes, *organizations, *persons])
    return {
        "source": "gdelt", "doc_id": row[0],
        "doc_date": dt.astimezone(EASTERN).date().isoformat(),
        "doc_time_utc": dt.isoformat().replace("+00:00", "Z"),
        "doc_date_utc": dt.date().isoformat(),
        "source_domain": domain, "url": row[4].strip(),
        "themes": themes, "organizations": organizations, "persons": persons,
        "locations": parse_locations(row[9])[:20],
        "gkg_tone": parse_tone(row[15]),
        "tone": parse_tone(row[15]),  # backwards-compatible original field
        "metadata_text": text, "text": text,  # legacy Spark compatibility alias
        "representation_type": "gkg_themes_orgs_persons",
        "direct_fed": direct, "broad_macro": broad,
        "shard_stamp": shard["stamp"], "shard_eastern_date": shard["eastern_date"],
        "filter_version": rules_hash,
    }


def validated_plan(path):
    result = []
    seen = set()
    with open(path, newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        needed = {"stamp", "eastern_date", "compressed_bytes", "md5", "url"}
        if not needed.issubset(set(reader.fieldnames or [])):
            raise ValueError(f"Plan must contain columns: {sorted(needed)}")
        for i, r in enumerate(reader, 2):
            stamp = str(r["stamp"]).strip()
            if not STAMP_RE.fullmatch(stamp):
                raise ValueError(f"Plan row {i}: bad stamp {stamp!r}")
            if stamp in seen:
                raise ValueError(f"Plan row {i}: duplicate {stamp}")
            seen.add(stamp)
            eastern_date = str(r["eastern_date"]).strip()
            if datetime.strptime(eastern_date, "%Y-%m-%d").date() != datetime.strptime(
                    stamp, "%Y%m%d%H%M%S").replace(tzinfo=timezone.utc).astimezone(EASTERN).date():
                raise ValueError(f"Plan row {i}: inconsistent Eastern day")
            parsed = urlsplit(r["url"].strip())
            match = ARCHIVE_RE.fullmatch(parsed.path)
            if (parsed.scheme != "https" or parsed.hostname != "data.gdeltproject.org"
                    or parsed.query or parsed.fragment or parsed.username or parsed.password
                    or not match or match.group(1) != stamp):
                raise ValueError(f"Plan row {i}: unexpected source URL")
            size = int(r["compressed_bytes"])
            md5 = r["md5"].lower().strip()
            if size < 1 or not MD5_RE.fullmatch(md5):
                raise ValueError(f"Plan row {i}: invalid size or MD5")
            result.append(dict(stamp=stamp, eastern_date=eastern_date,
                               compressed_bytes=size, md5=md5, url=parsed.geturl()))
    if not result:
        raise ValueError("Empty download plan")
    return sorted(result, key=lambda x: x["stamp"])


def load_rules(path):
    rules_bytes = Path(path).read_bytes()
    rules = json.loads(rules_bytes)
    required = {"version", "allow_domains", "fed_entities", "named_fed_officials",
                "policy_context", "broad_themes", "broad_keywords"}
    if not required.issubset(rules):
        raise ValueError(f"Rules missing keys: {sorted(required - set(rules))}")
    rules["allow_domains"] = sorted({normalize_domain(d) for d in rules["allow_domains"]})
    rules["broad_themes"] = list(rules["broad_themes"])
    return rules, hashlib.sha256(rules_bytes).hexdigest()


def normalized_prefix(prefix):
    prefix = prefix.strip("/")
    if not prefix or ".." in prefix.split("/"):
        raise ValueError("S3 prefix must be nonempty and not contain '..'")
    return prefix


def shard_manifest_key(prefix, stamp):
    return f"{prefix}/shards/{stamp}.json"


def fetch_archive(shard, dest, *, attempts=3):
    for attempt in range(1, attempts + 1):
        digest = hashlib.md5()  # official GDELT manifest uses MD5 integrity checks
        count = 0
        try:
            with requests.get(shard["url"], stream=True, timeout=(20, 90)) as resp:
                resp.raise_for_status()
                header = resp.headers.get("Content-Length")
                if header is not None and int(header) != shard["compressed_bytes"]:
                    raise ValueError("HTTP Content-Length differs from official plan")
                with open(dest, "wb") as target:
                    for block in resp.iter_content(chunk_size=1024 * 1024):
                        if block:
                            target.write(block)
                            digest.update(block)
                            count += len(block)
            if count != shard["compressed_bytes"]:
                raise ValueError(f"Compressed size mismatch: got {count}")
            if digest.hexdigest() != shard["md5"]:
                raise ValueError("GDELT MD5 mismatch")
            return
        except (requests.RequestException, ValueError, OSError):
            if attempt >= attempts:
                raise
            time.sleep(min(3 * attempt, 12))


def process_shard(shard, s3, bucket, out_prefix, manifest_prefix,
                  rules, rules_hash, attempts=3):
    stamp = shard["stamp"]
    keys = {
        corpus: f"{out_prefix}/{corpus}/{shard['eastern_date']}/gdelt_{stamp}.jsonl"
        for corpus in ("direct_fed", "broad_macro")
    }
    manifest = dict(stamp=stamp, url=shard["url"], eastern_date=shard["eastern_date"],
                    source_md5=shard["md5"], compressed_bytes=shard["compressed_bytes"],
                    filter_version=rules_hash, rules_label=rules["version"],
                    schema_version=RUN_SCHEMA_VERSION, status="failed", md5_ok=False,
                    parsed_rows=0, malformed_rows=0, matched_rows=0, direct_rows=0, broad_rows=0,
                    duplicate_doc_ids=0, duplicate_urls=0, output_keys={})
    try:
        with tempfile.TemporaryDirectory(prefix=f"gdelt_{stamp}_") as tmp:
            archive = Path(tmp) / f"{stamp}.zip"
            fetch_archive(shard, archive, attempts=attempts)
            manifest["md5_ok"] = True
            direct_path = Path(tmp) / "direct.jsonl"
            broad_path = Path(tmp) / "broad.jsonl"
            seen_ids = set()
            seen_urls = set()
            with zipfile.ZipFile(archive) as zf, \
                    open(direct_path, "w", encoding="utf-8") as direct_out, \
                    open(broad_path, "w", encoding="utf-8") as broad_out:
                data_files = [name for name in zf.namelist() if name.lower().endswith(".gkg.csv")]
                if len(data_files) != 1:
                    raise ValueError(f"Expected one GKG CSV member, found {data_files!r}")
                with zf.open(data_files[0], "r") as raw:
                    for line in raw:
                        line = line.rstrip(b"\r\n")
                        if not line:
                            continue
                        try:
                            # GKG fields are tab-separated. Literal quotes are data.
                            row = line.decode("utf-8-sig").split("\t")
                            doc = record_from_row(row, shard, rules, rules_hash)
                        except (UnicodeDecodeError, ValueError):
                            manifest["malformed_rows"] += 1
                            continue
                        manifest["parsed_rows"] += 1
                        if doc is None:
                            continue
                        if doc["doc_id"] in seen_ids:
                            manifest["duplicate_doc_ids"] += 1
                            continue
                        seen_ids.add(doc["doc_id"])
                        url_key = doc["url"].strip().lower()
                        if url_key and url_key in seen_urls:
                            manifest["duplicate_urls"] += 1
                            continue
                        if url_key:
                            seen_urls.add(url_key)
                        encoded = json.dumps(doc, ensure_ascii=False, separators=(",", ":")) + "\n"
                        broad_out.write(encoded)
                        manifest["broad_rows"] += 1
                        manifest["matched_rows"] += 1
                        if doc["direct_fed"]:
                            direct_out.write(encoded)
                            manifest["direct_rows"] += 1
            if manifest["parsed_rows"] == 0:
                raise ValueError("GKG archive contains zero valid rows")
            for corpus, count, path in (("broad_macro", manifest["broad_rows"], broad_path),
                                        ("direct_fed", manifest["direct_rows"], direct_path)):
                if count:
                    s3.upload_file(str(path), bucket, keys[corpus],
                                   ExtraArgs={"ContentType": "application/x-ndjson"})
                    manifest["output_keys"][corpus] = keys[corpus]
            manifest["status"] = "success" if manifest["matched_rows"] else "empty"
    except Exception as exc:
        manifest["error"] = f"{type(exc).__name__}: {exc}"[:1000]
        manifest["status"] = "failed"
    manifest["finished_utc"] = datetime.now(timezone.utc).isoformat()
    s3.put_object(Bucket=bucket, Key=shard_manifest_key(manifest_prefix, stamp),
                  Body=json.dumps(manifest, sort_keys=True).encode("utf-8"),
                  ContentType="application/json")
    return manifest


def checkpoint_valid(s3, bucket, manifest_prefix, shard, rules_hash):
    key = shard_manifest_key(manifest_prefix, shard["stamp"])
    try:
        obj = s3.get_object(Bucket=bucket, Key=key)
    except ClientError as exc:
        if exc.response.get("Error", {}).get("Code") in ("NoSuchKey", "404", "NotFound"):
            return None
        raise
    manifest = json.loads(obj["Body"].read())
    if (manifest.get("status") not in ("success", "empty")
            or not manifest.get("md5_ok")
            or manifest.get("filter_version") != rules_hash
            or manifest.get("schema_version") != RUN_SCHEMA_VERSION
            or manifest.get("source_md5") != shard["md5"]
            or manifest.get("url") != shard["url"]
            or manifest.get("compressed_bytes") != shard["compressed_bytes"]
            or manifest.get("parsed_rows", 0) <= 0):
        return None
    output_keys = manifest.get("output_keys", {})
    if manifest["status"] == "empty" and (output_keys or manifest.get("matched_rows") != 0):
        return None
    if manifest["status"] == "success" and not output_keys:
        return None
    for out_key in output_keys.values():
        try:
            s3.head_object(Bucket=bucket, Key=out_key)
        except ClientError as exc:
            if exc.response.get("Error", {}).get("Code") in ("404", "NotFound", "NoSuchKey"):
                return None
            raise
    return manifest


def write_run_manifest(s3, bucket, manifest_prefix, plan):
    """Aggregate ALL per-shard manifests (including previous sessions)."""
    local = []
    for shard in plan:
        try:
            obj = s3.get_object(Bucket=bucket, Key=shard_manifest_key(manifest_prefix, shard["stamp"]))
            local.append(json.loads(obj["Body"].read()))
        except ClientError as exc:
            if exc.response.get("Error", {}).get("Code") not in ("NoSuchKey", "404", "NotFound"):
                raise
    key = f"{manifest_prefix}/run_manifest.jsonl"
    data = "".join(json.dumps(item, sort_keys=True) + "\n" for item in local).encode("utf-8")
    s3.put_object(Bucket=bucket, Key=key, Body=data, ContentType="application/x-ndjson")
    return local, key


def main(argv=None):
    parser = argparse.ArgumentParser(description="Verified and restartable GDELT GKG ingest")
    parser.add_argument("--bucket", default=os.environ.get("MP_RUN_BUCKET") or os.environ.get("BUCKET"))
    parser.add_argument("--local-root", type=Path, help="Write shard and manifest keys under this local directory")
    parser.add_argument("--plan", required=True, help="Notebook-generated official HTTPS plan CSV")
    parser.add_argument("--out-prefix", required=True)
    parser.add_argument("--manifest-prefix", required=True)
    parser.add_argument("--workers", type=int, default=1)
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--max-shards", type=int, default=None)
    parser.add_argument("--rules", default=str(Path(__file__).with_name("gdelt_filter_rules_v1.json")))
    parser.add_argument("--attempts", type=int, default=3)
    args = parser.parse_args(argv)
    if not (args.bucket or args.local_root):
        parser.error("--bucket, MP_RUN_BUCKET, or --local-root is required")
    if args.workers < 1 or args.max_shards is not None and args.max_shards < 1:
        parser.error("--workers and --max-shards must be positive")
    out_prefix = normalized_prefix(args.out_prefix)
    manifest_prefix = normalized_prefix(args.manifest_prefix)
    if out_prefix == manifest_prefix or out_prefix.startswith(manifest_prefix + "/") or manifest_prefix.startswith(out_prefix + "/"):
        parser.error("Output and manifest prefixes must be separate")
    plan = validated_plan(args.plan)
    rules, rules_hash = load_rules(args.rules)
    s3 = LocalLake(args.local_root) if args.local_root else boto3.client("s3")
    print(f"Plan: {len(plan)} shards; rule set {rules['version']} SHA256 {rules_hash}", flush=True)
    pending = []
    skipped = 0
    for shard in plan:
        if args.resume:
            if checkpoint_valid(s3, args.bucket, manifest_prefix, shard, rules_hash):
                skipped += 1
                continue
        pending.append(shard)
    if args.max_shards is not None:
        pending = pending[:args.max_shards]
    print(f"Skip validated: {skipped}; process now: {len(pending)}; workers: {args.workers}", flush=True)
    results = []
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        futures = {pool.submit(process_shard, row, s3, args.bucket, out_prefix,
                               manifest_prefix, rules, rules_hash, args.attempts): row
                   for row in pending}
        for future in as_completed(futures):
            item = future.result()
            results.append(item)
            print(f"{item['stamp']}: {item['status']} parsed={item['parsed_rows']} "
                  f"direct={item['direct_rows']} broad={item['broad_rows']}", flush=True)
    all_rows, key = write_run_manifest(s3, args.bucket, manifest_prefix, plan)
    counts = {status: sum(x["status"] == status for x in all_rows)
              for status in ("success", "empty", "failed")}
    manifest_path = s3.root / key if args.local_root else f"s3://{args.bucket}/{key}"
    print(f"Manifest: {manifest_path}; recorded={len(all_rows)}/{len(plan)}, statuses={counts}")
    if any(x["status"] == "failed" for x in results):
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
